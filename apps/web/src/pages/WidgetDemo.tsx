import { useEffect, useState, type FormEvent } from 'react';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { Check, Copy } from 'lucide-react';
import { api } from '../lib/api';
import { useWorkspace } from '../context/WorkspaceContext';
import { useToast } from '../components/Toast';
import { EmptyState, NoWorkspaceState, Skeleton, WorkspaceErrorState, WorkspaceLoadingSkeleton, btnPrimary, btnSecondary, inputCls } from '../components/ui';

export default function WidgetDemo() {
  const { workspaceId, status: wsStatus, error: wsError, refetchWorkspaces } = useWorkspace();
  const toast = useToast();
  const queryClient = useQueryClient();
  const [copied, setCopied] = useState(false);

  const settingsQ = useQuery({
    queryKey: ['widget-settings', workspaceId],
    queryFn: () => api.getWidgetSettings(workspaceId!),
    enabled: !!workspaceId,
  });
  const settings = settingsQ.data ?? null;

  const [businessName, setBusinessName] = useState('');
  const [welcomeMessage, setWelcomeMessage] = useState('');
  const [primaryColor, setPrimaryColor] = useState('#7C3AED');
  const [enabled, setEnabled] = useState(true);
  const [originsText, setOriginsText] = useState('');

  // Fill the form once settings load (or fall back to defaults when none exist yet).
  const [hydratedFor, setHydratedFor] = useState<string | null>(null);
  useEffect(() => {
    if (settingsQ.isLoading || hydratedFor === workspaceId) return;
    setHydratedFor(workspaceId);
    if (settings) {
      setBusinessName(settings.business_name);
      setWelcomeMessage(settings.welcome_message);
      setPrimaryColor(settings.primary_color);
      setEnabled(settings.enabled);
      setOriginsText((settings.allowed_origins ?? []).join('\n'));
    }
  }, [settingsQ.isLoading, settings, workspaceId, hydratedFor]);

  const saveMut = useMutation({
    mutationFn: async () => {
      const payload = {
        business_name: businessName.trim(),
        welcome_message: welcomeMessage.trim(),
        primary_color: primaryColor.trim(),
        enabled,
        allowed_origins: originsText.split('\n').map((o) => o.trim()).filter(Boolean),
      };
      if (settings) return api.updateWidgetSettings(workspaceId!, payload);
      return api.createWidgetSettings(workspaceId!, payload);
    },
    onSuccess: () => {
      toast.success('Widget settings saved');
      void queryClient.invalidateQueries({ queryKey: ['widget-settings', workspaceId] });
    },
    onError: (err) => toast.error(`Could not save widget settings: ${(err as Error).message}`),
  });

if (wsStatus === 'auth-loading' || wsStatus === 'loading') return <WorkspaceLoadingSkeleton />;
if (wsStatus === 'error') return <WorkspaceErrorState message={wsError?.message} onRetry={refetchWorkspaces} />;
if (wsStatus === 'empty' || !workspaceId) return <NoWorkspaceState />;

  const embedUrl = settings
    ? `${window.location.origin}/widget-embed?key=${settings.public_key}`
    : '';
  const snippet = settings
    ? `<iframe src="${embedUrl}" title="Support chat" style="position:fixed;right:16px;bottom:16px;width:380px;height:560px;max-width:calc(100vw - 32px);border:0;z-index:9999"></iframe>`
    : '';

  const copySnippet = async () => {
    try {
      await navigator.clipboard.writeText(snippet);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 2000);
    } catch {
      toast.error('Copy failed — select the snippet text manually.');
    }
  };

  const submit = (e: FormEvent) => {
    e.preventDefault();
    if (!businessName.trim() || !welcomeMessage.trim()) return;
    saveMut.mutate();
  };

  return (
    <div className="space-y-4">
      <h1 className="text-2xl font-bold text-white">Chat Widget</h1>
      <p className="text-sm text-slate-400">
        Brand the embeddable chat widget for this workspace, then paste the snippet on any page.
        Visitors chat as guests; their messages land in your Inbox.
      </p>

      {settingsQ.isLoading ? (
        <Skeleton className="h-64" />
      ) : (
        <form onSubmit={submit} className="space-y-4 rounded-xl border border-slate-700/60 bg-card p-5">
          {!settings && (
            <p className="rounded-lg bg-primary/10 p-3 text-sm text-purple-200">
              No widget settings exist yet for this workspace — saving this form creates them (the public key is generated by the server).
            </p>
          )}
          <div className="grid gap-4 sm:grid-cols-2">
            <label className="block text-sm text-slate-300">Business name
              <input className={`${inputCls} mt-1`} required value={businessName} onChange={(e) => setBusinessName(e.target.value)} maxLength={100} />
            </label>
            <label className="block text-sm text-slate-300">Primary color
              <span className="mt-1 flex gap-2">
                <input type="color" value={primaryColor} onChange={(e) => setPrimaryColor(e.target.value)} aria-label="Primary color picker" className="h-10 w-12 cursor-pointer rounded-lg border border-slate-600 bg-navy" />
                <input className={inputCls} value={primaryColor} onChange={(e) => setPrimaryColor(e.target.value)} pattern="#[0-9a-fA-F]{6}" aria-label="Primary color hex value" />
              </span>
            </label>
          </div>
          <label className="block text-sm text-slate-300">Welcome message
            <textarea className={`${inputCls} mt-1`} required value={welcomeMessage} onChange={(e) => setWelcomeMessage(e.target.value)} maxLength={500} rows={2} />
          </label>
          <label className="flex items-center gap-2 text-sm text-slate-300">
            <input type="checkbox" checked={enabled} onChange={(e) => setEnabled(e.target.checked)} className="h-4 w-4 accent-purple-600" />
            Widget enabled (visitors can start chats)
          </label>
          <label className="block text-sm text-slate-300">Allowed origins (one per line)
            <textarea className={`${inputCls} mt-1`} value={originsText} onChange={(e) => setOriginsText(e.target.value)} rows={3} placeholder="One origin per line" />
            <span className="mt-1 block text-xs text-slate-500">
              Enforced server-side since Phase 2.1: only these exact origins (plus this app's own domain for previews) may embed and use the widget. Empty list = only this app's own domain. See docs/phase2-1-origins.md.
            </span>
            {settings && (settings.allowed_origins ?? []).length === 0 && (
              <span className="mt-1 block text-xs text-amber-300">
                No origins configured — only this app's own domain can embed the widget.
              </span>
            )}
          </label>
          <div className="flex justify-end">
            <button type="submit" disabled={saveMut.isPending} className={btnPrimary}>{saveMut.isPending ? 'Saving…' : settings ? 'Save settings' : 'Create widget'}</button>
          </div>
        </form>
      )}

      {settings && (
        <>
          <div className="rounded-xl border border-slate-700/60 bg-card p-5">
            <h2 className="font-semibold text-white">Embed snippet</h2>
            <p className="mt-1 text-sm text-slate-400">
              Public key: <code className="rounded bg-slate-800 px-1.5 py-0.5 font-mono text-xs text-slate-200">{settings.public_key}</code>
              {' '}— this key is an identifier only; it grants no data access by itself.
            </p>
            <pre className="mt-3 overflow-x-auto rounded-lg bg-navy p-3 text-xs text-slate-300">{snippet}</pre>
            <button onClick={copySnippet} className={`${btnSecondary} mt-3 flex items-center gap-2`}>
              {copied ? <Check className="h-4 w-4" /> : <Copy className="h-4 w-4" />} {copied ? 'Copied!' : 'Copy snippet'}
            </button>
          </div>
          <div className="rounded-xl border border-slate-700/60 bg-card p-5">
            <h2 className="font-semibold text-white">Live preview</h2>
            <p className="mt-1 text-sm text-slate-400">The widget below runs standalone in an iframe, exactly as it would on your site.</p>
            <div className="mt-3 h-[560px] overflow-hidden rounded-xl border border-slate-700">
              <iframe
                src={embedUrl}
                title="Chat widget preview"
                className="h-full w-full border-0"
                sandbox="allow-scripts allow-same-origin allow-forms"
              />
            </div>
          </div>
        </>
      )}
      {!settings && !settingsQ.isLoading && (
        <EmptyState title="No widget yet" description="Save the form above to create this workspace's widget and get its embed snippet." />
      )}
    </div>
  );
}
